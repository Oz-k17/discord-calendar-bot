/**
 * サムネイル候補の試し用素材と、その正解。
 *
 * シーン検出の `scenes.mjs` と同じ立場だが、**正解の置き方が違う**。
 * あちらは「どこで切り替わったか」で、こちらは「**どのコマなら使い物になるか**」。
 * 秒の点ではなく区間で持つことになるので、一覧を分けてある。
 *
 * ## 正解の置き方
 *
 * - `bad`  … **選んではいけない区間**（ボケている・黒い・白飛びしている・2 場面が重なっている）
 * - `good` … **ここから選んでほしい区間**（置いてある素材だけで数える）
 * - どちらにも入らない秒は「どちらでもよい」。フェードの傾きの途中のように、
 *   人でも意見が割れる所を無理に白黒へ倒すと、数字のほうが嘘になる。
 *
 * `from` を書いた素材は `scenes.mjs` の素材をそのまま使う（描き方を写さない）。
 * 新しく足したのは「同じ素材の中にボケたコマと鮮明なコマが並ぶ」形のものだけで、
 * それが無いと**選び分けを測る相手が居ない**（既存の素材はどれも尺ぜんたいが同じ調子）。
 */

import { SCENE_LENGTH, sceneFixture } from './scenes.mjs';

/**
 * 細かい肌理の強さ。**表紙の側では全素材に乗せる**（シーン検出の素材には乗っていない）。
 *
 * 理由は 2026-09-23 に測って分かった。肌理の無い合成の絵は隣どうしの差が 0.007 しかなく、
 * **10 画素ぶん動きボケを掛けても細かさが 3 桁目でしか動かない**。
 * 本物の映像で最初に失われるのは髪・布・草のような細かい所なので、
 * そこが無い素材でボケを測っても、測っているのは色の面のなだらかさでしかない。
 * 0.4 は「鮮明なコマの隣どうしの差が 0.03 台」になる強さ（実写を小さく縮めたときの見当）。
 */
export const THUMB_FINE = 0.4;

/**
 * 振り切ってから止まるカメラ。**前半はボケ、後半は鮮明。**
 *
 * ボケは後からぼかして作るのではなく、**シャッターが開いているあいだに
 * カメラが動いたぶん**として出る（`shutter`）。後からぼかす形だと、
 * ボケの量を作る側が決めてしまい、測る側はその数字を測り返すだけになる。
 *
 * 止まったあとも 0.05 画面/秒 でゆっくり流している。**完全に止めると
 * 後半のコマが 1 ビットまで同じ絵になり**、「似た絵を選ばない」を入れたとたん
 * 選ぶ先がボケた前半しか無くなる——素材の都合で結論が決まってしまう。
 */
