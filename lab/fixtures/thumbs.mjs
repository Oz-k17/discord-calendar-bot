/** 名前から素材を引く。`from` のものは `scenes.mjs` の中身をそのまま借りる。 */
export function thumbFixture(name) {
  const found = THUMB_FIXTURES.find((f) => (f.from ?? f.name) === name);
  if (!found) throw new Error(`素材 ${name} は知りません`);
  return resolveThumbFixture(found);
}

/** 一覧を、描ける形（`renderSpec` に渡せる形）へ直す。 */
export function resolveThumbFixture(entry) {
  const base = entry.from ? sceneFixture(entry.from) : entry;
  return {
    name: entry.from ?? entry.name,
    note: entry.note ?? base.note,
    hard: entry.hard ?? base.hard ?? false,
    cuts: base.cuts ?? [],
    // 肌理は**借りてきた素材にも乗せる**。乗せないと、黒つぶれや白飛びだけを
    // 相手にした数字になり、ボケの側と同じ物差しで並べられない。
    options: { fine: THUMB_FINE, ...(entry.options ?? base.options ?? {}) },
    bad: entry.bad ?? [],
    good: entry.good ?? [],
    shots: entry.shots ?? null,
  };
}

/** 一覧ぜんぶを描ける形で返す。 */
export function thumbFixtures() {
  return THUMB_FIXTURES.map(resolveThumbFixture);
}

/** 秒が区間の中に入っているか。境目は含む（正解の区間は閉じた区間として書いてある）。 */
export function inRanges(time, ranges) {
  return ranges.some((r) => time >= r.from && time <= r.to);
}
